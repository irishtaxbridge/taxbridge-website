/* Rebuilds search-index.js from the website pages.
   Run this after changing page content:  node build-search-index.js
   (This file does not need to be uploaded to the web host.) */
const fs = require('fs'), path = require('path');
const ENT = { amp: '&', euro: '€', copy: '©', eacute: 'é', gt: '>', lt: '<', middot: '·', ndash: '–', mdash: '—', quot: '"', nbsp: ' ', rsquo: '’' };
const clean = s => s.replace(/<[^>]+>/g, ' ')
    .replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(+n))
    .replace(/&(\w+);/g, (m, n) => ENT[n] || ' ')
    .replace(/\s+/g, ' ').replace(/ ([.,;:!?)])/g, '$1').trim();
// Must match slug() in search.js
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const index = [];
for (const file of fs.readdirSync(__dirname).filter(f => f.endsWith('.html')).sort()) {
    let html = fs.readFileSync(path.join(__dirname, file), 'utf8');
    const page = clean((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1] || file);
    const label = file === 'index.html' ? 'Home' : page;
    html = html.slice(html.indexOf('</header>') + 9);
    if (html.includes('<footer class="footer"')) html = html.slice(0, html.indexOf('<footer class="footer"'));
    if (file.startsWith('blog-') && html.includes('vote-widget')) html = html.slice(0, html.indexOf('vote-widget')).replace(/<[^<]*$/, '');
    html = html.replace(/<(script|style|svg|select|textarea|label|button(?! class="faq-question"))\b[\s\S]*?<\/\1>/g, ' ');
    if (file.startsWith('blog-')) html = html.replace(/<(nav|aside)\b[\s\S]*?<\/\1>/g, ' ');
    const re = /<(h[1-4]|summary|button class="faq-question")[^>]*>([\s\S]*?)<\/(?:h[1-4]|summary|button)>/g;
    const heads = [...html.matchAll(re)];
    heads.forEach((m, i) => {
        // The blog list repeats each article, which is already indexed from its own page
        if (file === 'blog.html' && m[1] !== 'h1') return;
        const title = clean(m[2]);
        const end = i + 1 < heads.length ? heads[i + 1].index : html.length;
        const text = file === 'blog.html' ? 'Tax tips, articles and guides.' : clean(html.slice(m.index + m[0].length, end).replace(/<[^>]*$/, '')).slice(0, 1200);
        if (title) index.push({ t: title, p: label, u: file + (m[1] === 'h1' ? '' : '#find=' + slug(title)), x: text });
    });
}
fs.writeFileSync(path.join(__dirname, 'search-index.js'),
    '/* Generated by build-search-index.js. Do not edit by hand. */\nwindow.TB_SEARCH_INDEX = ' + JSON.stringify(index, null, 0).replace(/\},\{/g, '},\n{') + ';\n');
console.log(index.length + ' search entries written');
